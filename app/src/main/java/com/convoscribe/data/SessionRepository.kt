package com.convoscribe.data

import androidx.room.withTransaction
import com.convoscribe.asr.TimedToken
import com.convoscribe.recording.RecordingStore
import java.io.File
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map

/**
 * Façade over [AppDatabase] for the rest of the app. Callers do not
 * touch the DAOs directly: this class owns the transactional rules
 * (e.g. applying a diarization result writes the per-segment speaker
 * index, replaces the speaker labels and flips the session status in
 * one transaction) and the on-disk side effects (the WAV file is
 * removed when the session is deleted).
 *
 * [recordingsDir] is `filesDir/recordings`; every session points at
 * `<recordingsDir>/<id>.wav` and that file is owned by this class
 * for the lifetime of the session.
 *
 * Also implements [RecordingStore] so the recording controller can
 * drive a session without taking a hard dependency on Room: the
 * controller talks to the interface and the production wiring
 * passes this repository.
 */
class SessionRepository(
    private val db: AppDatabase,
    private val recordingsDir: File
) : RecordingStore {
    private val sessionDao: SessionDao = db.sessionDao()
    private val segmentDao: SegmentDao = db.segmentDao()
    private val speakerDao: SpeakerDao = db.speakerDao()
    private val chatMessageDao: ChatMessageDao = db.chatMessageDao()
    private val markDao: MarkDao = db.markDao()

    /**
     * Create a new session row with [status] = RECORDING and
     * `audioPath = <recordingsDir>/<id>.wav`. The two writes happen
     * separately (insert first so we know the id, then update to
     * stamp the path) because the path depends on the autogenerated
     * primary key. The returned id is what the recorder uses to
     * create the WAV file. [numSpeakers] is normalised like
     * [setSessionSpeakerCount]; [participants] like [setParticipants].
     */
    override suspend fun createSession(
        title: String,
        language: String,
        numSpeakers: Int?,
        participants: List<String>?,
        summaryTemplate: String?,
        cleanedWith: String?
    ): Long {
        val row = SessionEntity(
            title = title,
            createdAt = System.currentTimeMillis(),
            language = language,
            status = SessionStatus.RECORDING,
            numSpeakers = normaliseSpeakerCount(numSpeakers),
            participants = ParticipantsCodec.encode(participants),
            summaryTemplate = summaryTemplate,
            cleanedWith = cleanedWith
        )
        val id = sessionDao.insert(row)
        sessionDao.update(row.copy(id = id, audioPath = File(recordingsDir, "$id.wav").absolutePath))
        return id
    }

    /**
     * Create a finished session from an imported file (issue #3) in
     * one transaction: the row (already `TRANSCRIBED`, with
     * [durationMs] and the [engine]/[model] that transcribed it), its
     * [segments], and [audio] moved to `<recordingsDir>/<id>.wav` as
     * the last step. Until this returns no row exists, so an import
     * that fails or is cancelled earlier leaves nothing behind; if the
     * move fails the row is rolled back. Options are normalised as in
     * [createSession].
     */
    suspend fun createImportedSession(
        title: String,
        language: String,
        numSpeakers: Int?,
        participants: List<String>?,
        durationMs: Long,
        engine: String,
        model: String,
        segments: List<SegmentPiece>,
        audio: File,
        summaryTemplate: String? = null
    ): Long = db.withTransaction {
        val row = SessionEntity(
            title = title,
            createdAt = System.currentTimeMillis(),
            durationMs = durationMs,
            language = language,
            status = SessionStatus.TRANSCRIBED,
            numSpeakers = normaliseSpeakerCount(numSpeakers),
            participants = ParticipantsCodec.encode(participants),
            summaryTemplate = summaryTemplate,
            asrEngine = engine,
            asrModel = model
        )
        val id = sessionDao.insert(row)
        val target = File(recordingsDir, "$id.wav")
        sessionDao.update(row.copy(id = id, audioPath = target.absolutePath))
        for (piece in segments) {
            segmentDao.insert(
                SegmentEntity(
                    sessionId = id,
                    startMs = piece.startMs,
                    endMs = piece.endMs,
                    text = piece.text,
                    speakerIndex = piece.speakerIndex,
                    tokens = TokenTimingCodec.encode(piece.tokens)
                )
            )
        }
        moveFile(audio, target)
        id
    }

    override suspend fun recordEngine(sessionId: Long, engine: String, model: String, continued: Boolean) {
        val row = sessionDao.get(sessionId) ?: return
        sessionDao.setEngine(
            sessionId,
            mergeEngineValue(row.asrEngine, engine, continued),
            mergeEngineValue(row.asrModel, model, continued)
        )
    }

    override suspend fun cleanedWith(sessionId: Long): String? = sessionDao.get(sessionId)?.cleanedWith

    override suspend fun sessionLanguage(sessionId: Long): String {
        val row = sessionDao.get(sessionId) ?: error("No session row for id $sessionId")
        return row.language
    }

    override suspend fun reopenSession(sessionId: Long) {
        sessionDao.setStatus(sessionId, SessionStatus.RECORDING)
    }

    /**
     * Append a transcript segment. Called by the ASR engine as
     * endpoints are detected. Returns the new segment id.
     */
    override suspend fun addSegment(
        sessionId: Long,
        startMs: Long,
        endMs: Long,
        text: String,
        tokens: List<TimedToken>
    ): Long = segmentDao.insert(
        SegmentEntity(
            sessionId = sessionId,
            startMs = startMs,
            endMs = endMs,
            text = text,
            tokens = TokenTimingCodec.encode(tokens)
        )
    )

    override suspend fun addMark(sessionId: Long, atMs: Long, note: String?): Long = markDao.insert(
        MarkEntity(
            sessionId = sessionId,
            atMs = atMs.coerceAtLeast(0L),
            note = normaliseNote(note),
            createdAt = System.currentTimeMillis()
        )
    )

    override suspend fun countMarks(sessionId: Long): Int = markDao.count(sessionId)

    /** The session's marks (issue #30), in recorded-time order. */
    fun observeMarks(sessionId: Long): Flow<List<MarkEntity>> = markDao.observeForSession(sessionId)

    suspend fun getMarks(sessionId: Long): List<MarkEntity> = markDao.getForSession(sessionId)

    /**
     * Replace a mark's note. It is trimmed and cut to
     * [MARK_NOTE_MAX_LEN]; a blank note removes it.
     */
    suspend fun setMarkNote(markId: Long, note: String?) = markDao.setNote(markId, normaliseNote(note))

    suspend fun deleteMark(markId: Long) = markDao.delete(markId)

    /**
     * Recording finished. Stamp the duration and move the session
     * to [SessionStatus.TRANSCRIBED]; the service then diarizes it or
     * leaves it pending.
     */
    override suspend fun finishRecording(sessionId: Long, durationMs: Long) {
        sessionDao.get(sessionId)?.let { row ->
            sessionDao.update(
                row.copy(
                    durationMs = durationMs,
                    status = SessionStatus.TRANSCRIBED
                )
            )
        }
    }

    /**
     * Look up the WAV path the recorder should write to for
     * [sessionId]. Returns the `audioPath` column stamped by
     * [createSession]. Throws [IllegalStateException] if the
     * session is unknown: that should never happen because the
     * recorder only calls this with an id returned by
     * [createSession] moments earlier, and we want a loud failure
     * instead of a silent default.
     */
    override suspend fun audioPath(sessionId: Long): String {
        val row = sessionDao.get(sessionId)
            ?: error("No session row for id $sessionId; was it deleted mid-recording?")
        return row.audioPath
    }

    /**
     * Delete the session, the WAV file, its cleaned copy (issue #37)
     * and (via `ON DELETE CASCADE`) the segments, speakers, chat
     * messages and marks. Idempotent: deleting an unknown id is a
     * no-op and silently returns.
     */
    suspend fun deleteSession(id: Long) {
        val row = sessionDao.get(id)
        if (row != null && row.audioPath.isNotBlank()) {
            File(row.audioPath).delete()
            row.cleanAudioFile().delete()
        }
        sessionDao.delete(id)
    }

    /**
     * Stop treating [sessionId] as cleaned (issue #37): forget the
     * model and delete the cleaned recording, so playback and the
     * next re-transcription use the original again. The transcript is
     * left as it is.
     */
    suspend fun removeCleaning(sessionId: Long) {
        val row = sessionDao.get(sessionId) ?: return
        sessionDao.setCleanedWith(sessionId, null)
        if (row.audioPath.isNotBlank()) row.cleanAudioFile().delete()
    }

    // --- Pass-throughs for observe/get ---

    fun observeAllSessions(): Flow<List<SessionEntity>> = sessionDao.observeAll()

    fun observeSession(id: Long): Flow<SessionEntity?> = sessionDao.observe(id)

    suspend fun getSession(id: Long): SessionEntity? = sessionDao.get(id)

    fun observeSegments(sessionId: Long): Flow<List<SegmentEntity>> = segmentDao.observeForSession(sessionId)

    suspend fun getSegments(sessionId: Long): List<SegmentEntity> = segmentDao.getForSession(sessionId)

    fun observeSpeakers(sessionId: Long): Flow<List<SpeakerEntity>> = speakerDao.observeForSession(sessionId)

    /** Detected speakers per session id, for the session list; undiarized sessions are absent. */
    fun observeSpeakerCounts(): Flow<Map<Long, Int>> =
        speakerDao.observeCounts().map { rows -> rows.associate { it.sessionId to it.count } }

    suspend fun getSpeakers(sessionId: Long): List<SpeakerEntity> = speakerDao.getForSession(sessionId)

    fun observeChat(sessionId: Long, kind: MessageKind): Flow<List<ChatMessageEntity>> =
        chatMessageDao.observe(sessionId, kind)

    /**
     * Observe the chat messages of [kind] for [sessionId]. Mirrors
     * [observeChat] — kept as a separate name so the summary /
     * Q&A ViewModels can talk about "messages" instead of
     * "chat history" without renaming the original.
     */
    fun observeMessages(sessionId: Long, kind: MessageKind): Flow<List<ChatMessageEntity>> =
        chatMessageDao.observe(sessionId, kind)

    suspend fun deleteChatKind(sessionId: Long, kind: MessageKind) = chatMessageDao.deleteKind(sessionId, kind)

    suspend fun addChatMessage(entity: ChatMessageEntity): Long = chatMessageDao.insert(entity)

    /**
     * Insert a chat message and return its autogenerated id. The
     * `createdAt` timestamp is stamped here (rather than expected
     * from the caller) so every writer agrees on "now" and the
     * `ORDER BY createdAt ASC, id ASC` ordering used by
     * [observe] is stable across the app.
     */
    suspend fun addMessage(
        sessionId: Long,
        kind: MessageKind,
        role: MessageRole,
        content: String,
        templateName: String? = null,
        coveredMs: Long? = null,
        totalMs: Long? = null
    ): Long = chatMessageDao.insert(
        ChatMessageEntity(
            sessionId = sessionId,
            kind = kind,
            role = role,
            content = content,
            createdAt = System.currentTimeMillis(),
            templateName = templateName,
            coveredMs = coveredMs,
            totalMs = totalMs
        )
    )

    /**
     * Remove every chat message of [kind] for [sessionId].
     * Equivalent to [deleteChatKind] — provided as the
     * "clear-then-add" partner of [addMessage] so the summary
     * regeneration flow reads symmetrically.
     */
    suspend fun clearMessages(sessionId: Long, kind: MessageKind) {
        chatMessageDao.deleteKind(sessionId, kind)
    }

    suspend fun setSegmentSpeaker(segmentId: Long, speakerIndex: Int?) = segmentDao.setSpeaker(segmentId, speakerIndex)

    /**
     * Replace line [lineId]'s text with [text], keeping the timings of
     * the words that did not change (issue #26). `null`, and nothing
     * written, when the text is blank or unchanged or the line is gone.
     */
    suspend fun editLineText(lineId: Long, text: String): EditUndo? = edit(lineId) { line, undo ->
        val edited = TranscriptEditor.editText(line, text) ?: return@edit null
        segmentDao.update(edited)
        undo
    }

    /** Give line [lineId] the session's existing speaker [speakerIndex]. */
    suspend fun setLineSpeaker(lineId: Long, speakerIndex: Int): EditUndo? = edit(lineId) { line, undo ->
        if (line.speakerIndex == speakerIndex && line.speakerEdited) return@edit null
        segmentDao.update(TranscriptEditor.setSpeaker(line, speakerIndex))
        undo
    }

    /**
     * Give line [lineId] a speaker the session does not have yet, named
     * [label] (trimmed; blank means the default `"Speaker N"`).
     */
    suspend fun setLineNewSpeaker(lineId: Long, label: String): EditUndo? = edit(lineId) { line, undo ->
        val index = (speakerDao.getForSession(line.sessionId).maxOfOrNull { it.speakerIndex } ?: -1) + 1
        val name = label.trim().ifEmpty { defaultSpeakerLabel(index) }
        speakerDao.upsert(listOf(SpeakerEntity(sessionId = line.sessionId, speakerIndex = index, label = name)))
        segmentDao.update(TranscriptEditor.setSpeaker(line, index))
        undo.copy(addedSpeaker = index)
    }

    /** Join line [lineId] and the line after it; `null` for the last line. */
    suspend fun mergeWithNext(lineId: Long): EditUndo? = edit(lineId) { line, undo ->
        val lines = segmentDao.getForSession(line.sessionId)
        val next = lines.getOrNull(lines.indexOfFirst { it.id == lineId } + 1) ?: return@edit null
        segmentDao.update(TranscriptEditor.merge(line, next))
        segmentDao.delete(next.id)
        undo.copy(before = listOf(line, next))
    }

    /**
     * Split line [lineId] in two at the word boundary nearest [offset]
     * (a character position in its text); `null` for a one-word line.
     */
    suspend fun splitLine(lineId: Long, offset: Int): EditUndo? = edit(lineId) { line, undo ->
        val (first, second) = TranscriptEditor.split(line, offset) ?: return@edit null
        segmentDao.update(first)
        undo.copy(insertedIds = listOf(segmentDao.insert(second)))
    }

    /** Remove line [lineId] from the transcript. */
    suspend fun deleteLine(lineId: Long): EditUndo? = edit(lineId) { _, undo ->
        segmentDao.delete(lineId)
        undo
    }

    /**
     * Put back what the edit behind [undo] changed: the lines as they
     * were, without the rows and speaker it added, and the session's
     * edited flag as it was. One transaction.
     */
    suspend fun undo(undo: EditUndo) {
        db.withTransaction {
            undo.insertedIds.forEach { segmentDao.delete(it) }
            for (row in undo.before) {
                if (segmentDao.get(row.id) != null) segmentDao.update(row) else segmentDao.insert(row)
            }
            undo.addedSpeaker?.let { speakerDao.delete(undo.sessionId, it) }
            sessionDao.setTranscriptEdited(undo.sessionId, undo.wasEdited)
        }
    }

    /**
     * Run one hand edit of line [lineId] in a transaction and mark the
     * session edited. [block] gets the line and an [EditUndo] holding
     * it as it was, and returns that (amended) or `null` when it
     * changed nothing.
     */
    private suspend fun edit(lineId: Long, block: suspend (SegmentEntity, EditUndo) -> EditUndo?): EditUndo? =
        db.withTransaction {
            val line = segmentDao.get(lineId) ?: return@withTransaction null
            val wasEdited = sessionDao.get(line.sessionId)?.transcriptEdited ?: false
            val undo = block(line, EditUndo(sessionId = line.sessionId, before = listOf(line), wasEdited = wasEdited))
            if (undo != null) sessionDao.setTranscriptEdited(line.sessionId, true)
            undo
        }

    /**
     * Rename the speaker identified by [speakerIndex] within
     * [sessionId]. The label is trimmed and a blank result is
     * ignored — the existing label stays in place so the user
     * cannot accidentally blank out a speaker. The DAO's
     * `UPDATE` is a no-op for an unknown (sessionId, index)
     * pair, which is the behaviour we want: renaming a speaker
     * the diarizer never produced must not throw.
     */
    suspend fun renameSpeaker(sessionId: Long, speakerIndex: Int, label: String) {
        val trimmed = label.trim()
        if (trimmed.isEmpty()) return
        speakerDao.rename(sessionId, speakerIndex, trimmed)
    }

    /**
     * Rename the session. The new title is trimmed, blanks are
     * ignored (the existing title is kept), and titles longer
     * than 100 characters are truncated to the first 100
     * characters — long enough for a meaningful label, short
     * enough to fit the home-screen list row. Unknown ids are a
     * no-op because the DAO's `UPDATE` does nothing on a missing
     * row.
     */
    suspend fun renameSession(sessionId: Long, title: String) {
        val trimmed = title.trim()
        if (trimmed.isEmpty()) return
        val capped = if (trimmed.length > SESSION_TITLE_MAX_LEN) {
            trimmed.substring(0, SESSION_TITLE_MAX_LEN)
        } else {
            trimmed
        }
        sessionDao.rename(sessionId, capped)
    }

    /**
     * Flip [id]'s status to [status]. Used by the diarization use
     * case (`DIARIZING` on entry, `DIARIZED` via
     * [applyDiarization], `DIARIZATION_FAILED` on error) and by
     * the crash-recovery loop (`RECORDING`/`DIARIZING` →
     * `TRANSCRIBED`). Unknown ids are a no-op because the DAO's
     * `UPDATE` statement does nothing on a missing row.
     */
    suspend fun setStatus(id: Long, status: SessionStatus) {
        sessionDao.setStatus(id, status)
    }

    /**
     * Remember the speaker count chosen for [id] ("Re-identify
     * speakers"): `-1` automatic, `1..10` fixed, `null` back to the
     * Settings default. Every later diarization of the session uses
     * it, including the one after a continued recording.
     */
    suspend fun setSessionSpeakerCount(id: Long, numSpeakers: Int?) {
        sessionDao.setNumSpeakers(id, normaliseSpeakerCount(numSpeakers))
    }

    /**
     * Set who is expected in [id] (enrolled names), or `null` for
     * anyone. Names are trimmed and de-duplicated; an empty list
     * means anyone. Takes effect on the next diarization.
     */
    suspend fun setParticipants(id: Long, participants: List<String>?) {
        sessionDao.setParticipants(id, ParticipantsCodec.encode(participants))
    }

    /**
     * Summary template [key] for this session (issue #27), chosen on
     * the Summary tab; the next summary uses it.
     */
    suspend fun setSummaryTemplate(id: Long, key: String) {
        sessionDao.setSummaryTemplate(id, key)
    }

    /**
     * Swap [sessionId]'s transcript for [segments] after a
     * re-transcription in [language]: the old segments are deleted,
     * the new ones inserted, the language and [engine]/[model]
     * replaced and the session moved to `TRANSCRIBED`, all in one
     * transaction, so a failure leaves the previous transcript
     * intact. Hand edits are gone with the old lines, so the session
     * no longer counts as edited. Speaker rows are kept so a following diarization can
     * carry custom names over (each piece's [SegmentPiece.speakerIndex]
     * says which old speaker it overlapped).
     *
     * With [cleaned] (issue #37) the transcript was made from a
     * cleaned copy of the audio: the file is moved into place as the
     * session's cleaned recording, as the last step of the same
     * transaction, and the session is marked cleaned with its model.
     */
    suspend fun replaceTranscript(
        sessionId: Long,
        language: String,
        segments: List<SegmentPiece>,
        engine: String,
        model: String,
        cleaned: CleanedAudio? = null
    ) {
        db.withTransaction {
            sessionDao.deleteSegments(sessionId)
            for (piece in segments) {
                segmentDao.insert(
                    SegmentEntity(
                        sessionId = sessionId,
                        startMs = piece.startMs,
                        endMs = piece.endMs,
                        text = piece.text,
                        speakerIndex = piece.speakerIndex,
                        tokens = TokenTimingCodec.encode(piece.tokens)
                    )
                )
            }
            sessionDao.setLanguage(sessionId, language)
            sessionDao.setEngine(sessionId, engine, model)
            sessionDao.setTranscriptEdited(sessionId, false)
            sessionDao.setStatus(sessionId, SessionStatus.TRANSCRIBED)
            if (cleaned != null) {
                val row = sessionDao.get(sessionId) ?: error("No session row for id $sessionId")
                sessionDao.setCleanedWith(sessionId, cleaned.model)
                moveFile(cleaned.file, row.cleanAudioFile())
            }
        }
    }

    /**
     * Stamp [durationMs] on [id]. Used by the crash-recovery loop
     * to compute the duration of a WAV that was left in a
     * half-closed state when the process was killed; the recorder
     * itself calls [finishRecording], which both sets the duration
     * and flips the status. Unknown ids are a no-op.
     */
    suspend fun setDuration(id: Long, durationMs: Long) {
        sessionDao.updateDuration(id, durationMs)
    }

    /**
     * Every session currently in [status]. Used by the
     * crash-recovery loop (TASK-19) to find sessions left in
     * `RECORDING` (process killed mid-capture) or `DIARIZING`
     * (process killed mid-diarization). The result is a snapshot
     * taken at call time — the loop iterates it without holding
     * any database cursor, so the writes it issues do not race
     * with a future caller re-fetching the same rows.
     */
    suspend fun sessionsWithStatus(status: SessionStatus): List<SessionEntity> {
        return sessionDao.findByStatus(status)
    }

    /**
     * Persist a diarization result. [assignments] maps a segment id
     * to its speaker index (or `null` for unlabelled). [speakerCount]
     * is the number of distinct speakers the diarizer detected, used
     * to generate the "Speaker 1..N" labels. [labels] is an optional
     * map of `speakerIndex → user-visible name`; any index present
     * here keeps that name instead of falling back to
     * `"Speaker ${index + 1}"`. Unknown indices are silently
     * ignored — the diarizer is the authority on the set of
     * speakers, the label map just renames some of them.
     *
     * [replacements] maps a segment id to the pieces it was split
     * into at speaker changes; that row is deleted and the pieces are
     * inserted with their own speaker. Segments not in it keep their
     * row and take their index from [assignments].
     *
     * Everything happens in one transaction so a crash mid-write
     * does not leave the session half-diarized: either every
     * segment has the new index and the speakers table is replaced,
     * or nothing changed.
     */
    suspend fun applyDiarization(
        sessionId: Long,
        assignments: Map<Long, Int?>,
        speakerCount: Int,
        labels: Map<Int, String> = emptyMap(),
        replacements: Map<Long, List<SegmentPiece>> = emptyMap()
    ) {
        db.withTransaction {
            assignments.forEach { (segmentId, speakerIndex) ->
                segmentDao.setSpeaker(segmentId, speakerIndex)
            }
            replacements.forEach { (segmentId, pieces) ->
                segmentDao.delete(segmentId)
                for (piece in pieces) {
                    segmentDao.insert(
                        SegmentEntity(
                            sessionId = sessionId,
                            startMs = piece.startMs,
                            endMs = piece.endMs,
                            text = piece.text,
                            speakerIndex = piece.speakerIndex,
                            tokens = TokenTimingCodec.encode(piece.tokens)
                        )
                    )
                }
            }
            speakerDao.deleteForSession(sessionId)
            val rows = (0 until speakerCount).map { i ->
                SpeakerEntity(
                    sessionId = sessionId,
                    speakerIndex = i,
                    label = labels[i] ?: defaultSpeakerLabel(i)
                )
            }
            if (rows.isNotEmpty()) {
                speakerDao.upsert(rows)
            }
            sessionDao.setStatus(sessionId, SessionStatus.DIARIZED)
        }
    }

    companion object {
        /**
         * Move [from] to [to]: a rename when both are on one file
         * system, otherwise copy then delete. A failed copy removes the
         * partial [to] and rethrows.
         */
        internal fun moveFile(from: File, to: File) {
            if (from.renameTo(to)) return
            try {
                from.copyTo(to, overwrite = true)
            } catch (e: Exception) {
                to.delete()
                throw e
            }
            from.delete()
        }

        /** `-1` automatic, `1..10` fixed, `null` kept (follow Settings). */
        /** Longest note a mark keeps; marks are for a few words, not paragraphs. */
        const val MARK_NOTE_MAX_LEN: Int = 200

        internal fun normaliseNote(note: String?): String? =
            note?.trim()?.take(MARK_NOTE_MAX_LEN)?.trim()?.takeIf { it.isNotEmpty() }

        internal fun normaliseSpeakerCount(numSpeakers: Int?): Int? =
            numSpeakers?.let { if (it < 1) -1 else it.coerceAtMost(10) }

        /**
         * [previous] engine/model value of a session merged with the one
         * that just ran: unchanged when it already lists [current],
         * otherwise `"<previous> + <current>"`. A [continued] session
         * with no value predates the column, so it reads as unknown.
         */
        internal fun mergeEngineValue(previous: String?, current: String, continued: Boolean): String = when {
            previous.isNullOrBlank() -> if (continued) "$UNKNOWN_ENGINE + $current" else current
            current in previous.split(" + ") -> previous
            else -> "$previous + $current"
        }

        /**
         * Upper bound on the user-editable session title. Long
         * enough for a meaningful label (most call this a meeting
         * name or a one-line summary), short enough to fit the
         * home-screen row without ellipsising every entry.
         * Applied by [renameSession] so the DAO never has to
         * worry about caps.
         */
        const val SESSION_TITLE_MAX_LEN: Int = 100

        /** Shown for an engine or model a session did not record. */
        const val UNKNOWN_ENGINE: String = "unknown"
    }
}

/**
 * What [SessionRepository.undo] needs to take back one hand edit:
 * the lines it changed or removed, as they were ([before]), the rows
 * it added, the speaker it created, and whether the session already
 * counted as edited.
 */
data class EditUndo(
    val sessionId: Long,
    val before: List<SegmentEntity>,
