package com.convoscribe.recording

import com.convoscribe.asr.TimedToken

/**
 * Persistence façade [RecordingController] uses to keep its
 * session/segment lifecycle in the database. Splitting it off from
 * the rest of [com.convoscribe.data.SessionRepository] keeps the
 * controller unit-testable with a tiny in-memory fake that does not
 * need Room or Robolectric.
 *
 * Every method is `suspend` because the real implementation talks
 * to Room's IO dispatcher under the hood.
 */
interface RecordingStore {

    /**
     * Create a fresh session row in `RECORDING` status and return
     * its autogenerated id. The title is what the UI shows in the
     * session list; the language tells the diarization worker
     * which model to use. [numSpeakers] (`-1` automatic) and
     * [participants] (`null` anyone) are the per-conversation
     * options chosen before Start, as is [summaryTemplate] (`null`
     * follows the default).
     */
    suspend fun createSession(
        title: String,
        language: String,
        numSpeakers: Int? = null,
        participants: List<String>? = null,
        summaryTemplate: String? = null
    ): Long

    /**
     * Remember that [engine] and [model] transcribed (part of)
     * [sessionId]. A session [continued] with a different engine or
     * model keeps both, joined by `" + "`; one recorded before engines
     * were kept shows as `"unknown + <engine>"`.
     */
    suspend fun recordEngine(sessionId: Long, engine: String, model: String, continued: Boolean = false)

    /**
     * Language [sessionId] was recorded in, so continuing it uses
     * the same ASR model even if Settings changed since. Throws
     * [IllegalStateException] for an unknown session.
     */
    suspend fun sessionLanguage(sessionId: Long): String

    /**
     * Flip an existing session back to `RECORDING` so more audio can
     * be appended (see [RecordingController.start]). Called only
     * once the transcriber and the WAV file are open, so a failed
     * continue leaves the session as it was. [finishRecording] ends
     * it again; crash recovery treats it like any interrupted
     * recording.
     */
    suspend fun reopenSession(sessionId: Long)

    /**
     * Absolute path of the WAV file the recorder should write to
     * for [sessionId]. Implementation-specific: production returns
     * the `audioPath` stamped by [createSession] (a path under the
     * app's `filesDir/recordings/`), tests return a path inside a
     * temporary folder.
     */
    suspend fun audioPath(sessionId: Long): String

    /**
     * Append one transcript segment (a closed utterance produced by
     * the ASR endpoint) and return its id. Called by the controller
     * as soon as a [com.convoscribe.asr.TranscriptEvent.Final] is
     * observed, so partial results are never lost on a crash.
     * [tokens] carry absolute times within the recording.
     */
    suspend fun addSegment(
        sessionId: Long,
        startMs: Long,
        endMs: Long,
        text: String,
        tokens: List<TimedToken> = emptyList()
    ): Long

    /**
     * Mark the moment [atMs] of [sessionId]'s recorded audio, with an
     * optional [note] (issue #30), and return the mark's id.
     */
    suspend fun addMark(sessionId: Long, atMs: Long, note: String? = null): Long

    /** How many marks [sessionId] has, so a continued session counts on from them. */
    suspend fun countMarks(sessionId: Long): Int

    /**
     * Stamp the final duration and flip the session to `TRANSCRIBED`
     * so the diarization worker picks it up. Called by
     * [RecordingController.stop] on a clean exit, and by the
     * error path on a crash so partial transcripts still surface
     * in the session list.
     */
    suspend fun finishRecording(sessionId: Long, durationMs: Long)
}
